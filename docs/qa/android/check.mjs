import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createAndroidAudioElement, hasAndroidAudioBridge } from "../../../src/components/MusicPlayer/media/androidAudioElement.mjs";
const sent = [];
const bridge = { postMessage: value => sent.push(JSON.parse(value)) };
globalThis.window = { HayKasaAndroidMedia: bridge };
globalThis.location = { origin: "https://untrusted.example" };
assert.equal(hasAndroidAudioBridge(), false);
assert.equal(createAndroidAudioElement(), null);
globalThis.location.origin = "https://haykasa.vercel.app";
globalThis.document = { createElement: () => Object.assign(new EventTarget(), { style: {}, setAttribute() {}, remove() {}, removeAttribute() {} }) };
const media = createAndroidAudioElement("Test song");
assert(media.isAndroidNativeMedia);
const events = [];
for (const name of ["loadedmetadata", "playing", "pause", "timeupdate", "ended", "error"]) media.addEventListener(name, () => events.push(name));
media.src = "https://haykasa.vercel.app/v1/assets/0123456789abcdef0123456789abcdef?signature=synthetic";
media.load();
const load = sent.at(-1);
assert.equal(load.action, "load"); assert.equal(load.title, "Test song");
assert.equal(media.currentSrc, media.src);
bridge.onmessage({ data: JSON.stringify({ id: "wrong", event: "ready", duration: 200 }) });
assert.deepEqual(events, []);
bridge.onmessage({ data: JSON.stringify({ id: load.id, event: "ready", duration: 200, position: 0 }) });
assert.equal(media.duration, 200); assert.deepEqual(events, ["loadedmetadata"]);
bridge.onmessage({ data: JSON.stringify({ id: load.id, event: "ready", duration: 200, position: 0 }) });
assert.equal(events.length, 1, "A seek becoming ready must not reset the deck");
media.currentTime = 42; assert.equal(sent.at(-1).action, "seek");
media.volume = .4; media.muted = false;
assert.equal(sent.at(-1).value, .4);
await media.play(); assert.equal(sent.at(-1).action, "play");
bridge.onmessage({ data: JSON.stringify({ id: load.id, event: "playing", duration: 200, position: 43 }) });
assert.equal(media.paused, false); assert.equal(media.currentTime, 43);
media.pause(); assert.equal(sent.at(-1).action, "pause");
bridge.onmessage({ data: JSON.stringify({ id: load.id, event: "pause", duration: 200, position: 43 }) });
assert.equal(media.paused, true);
bridge.onmessage({ data: JSON.stringify({ id: load.id, event: "ended", duration: 200, position: 200 }) });
assert.equal(media.ended, true);
media.removeAttribute("src"); const before = sent.length; media.load(); assert.equal(sent.length, before);
media.remove(); assert.equal(sent.at(-1).action, "release");
bridge.onmessage({ data: JSON.stringify({ id: load.id, event: "playing", position: 2 }) });
assert.equal(media.currentTime, 200, "Released bridge listeners cannot change state");
console.log("Android audio bridge checks passed: origin, metadata, seek, output volume, pause, end, stale events and cleanup.");

